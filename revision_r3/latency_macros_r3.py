"""latency_macros_r3.py -- turns bench_r3/latency_r3_stats.json (from
analyze_bench_r3.py) into LaTeX macros used by Section VIII of
docs/JISA_R3_overleaf.tex. Output: bench_r3/latency_r3_macros.tex
(paste its contents into the manuscript preamble)."""
import json, pathlib
import numpy as np
B = pathlib.Path(__file__).resolve().parent / "bench_r3"
d = json.loads((B / "latency_r3_stats.json").read_text())
BS = chr(92)
def mac(name, v, digits=1):
    return f"{BS}newcommand{{{BS}{name}}}{{{v:.{digits}f}}}"
def pv(p):
    # rendered after "$p$": math mode, so "<" is not typeset as an inverted "!" (OT1)
    return "$<0.001$" if p < 0.001 else f"$={p:.3f}$"
MODES = (("none", "None"), ("no_middleware", "View"), ("full", "Full"))
M = []
for ph, tag in (("sequential", "Seq"), ("concurrent", "Conc")):
    cl = d[ph]["client"]
    for m, t in MODES:
        M += [mac(f"Lat{tag}{t}Med", cl[m]["median"]), mac(f"Lat{tag}{t}Pnf", cl[m]["p95"]),
              mac(f"Lat{tag}{t}Pnn", cl[m]["p99"]), mac(f"Lat{tag}{t}N", cl[m]["n"], 0)]
        rr = d[ph]["per_rep_median"][m]
        M += [mac(f"Lat{tag}{t}RepMin", min(rr)), mac(f"Lat{tag}{t}RepMax", max(rr))]
        if m in d[ph].get("server", {}):
            M.append(mac(f"Lat{tag}{t}SrvMed", d[ph]["server"][m]["median"]))
    for k, t in (("full_vs_none", "FullNone"), ("no_middleware_vs_none", "ViewNone"), ("full_vs_no_middleware", "FullView")):
        c = d[ph][k]
        M += [mac(f"Lat{tag}{t}Diff", c["median_diff_ms"]), mac(f"Lat{tag}{t}Lo", c["median_diff_ci95"][0]),
              mac(f"Lat{tag}{t}Hi", c["median_diff_ci95"][1]), mac(f"Lat{tag}{t}Rel", c["rel_median_pct"], 0),
              mac(f"Lat{tag}{t}HL", c["hodges_lehmann_ms"]),
              f"{BS}newcommand{{{BS}Lat{tag}{t}P}}{{{pv(c['mwu_p'])}}}"]
for m, t in MODES:
    M.append(mac(f"Rps{t}", float(np.mean(d["throughput_rps"][m]))))
M.append(f"{BS}newcommand{{{BS}LatNonOK}}{{{d['non_200']['sequential'] + d['non_200']['concurrent']}}}")
(B / "latency_r3_macros.tex").write_text("% generated by latency_macros_r3.py -- paste into the preamble\n" + "\n".join(M) + "\n")
print("\n".join(M))
